/**
 * @module modules/conversations/persistence/Thread
 * @description Mongoose persistence model for AI agent conversation threads.
 * Replaces monolithic Chat.messages array with a normalized, non-monolithic thread entity.
 * Owned strictly by authenticated user (owner: req.user._id).
 */

import mongoose from 'mongoose';
import { BASE_SCHEMA_OPTIONS } from '../../../infrastructure/database/schemaOptions.js';
import { CHAT_CONSTANTS, CONVERSATION_CONSTANTS } from '../../../utils/constants.js';

const threadConfigSchema = new mongoose.Schema(
  {
    model: {
      type: String,
      default: CHAT_CONSTANTS.DEFAULT_MODEL,
      trim: true,
    },
    provider: {
      type: String,
      default: 'google',
      trim: true,
    },
    thinkingBudget: {
      type: Number,
      default: CHAT_CONSTANTS.DEFAULT_THINKING_BUDGET,
      min: CHAT_CONSTANTS.MIN_THINKING_BUDGET,
      max: CHAT_CONSTANTS.MAX_THINKING_BUDGET,
    },
    temperature: {
      type: Number,
      min: 0,
      max: 2,
      default: CHAT_CONSTANTS.DEFAULT_TEMPERATURE,
    },
    language: {
      type: String,
      enum: CHAT_CONSTANTS.SUPPORTED_LANGUAGES,
      default: CHAT_CONSTANTS.DEFAULT_LANGUAGE,
    },
  },
  { _id: false }
);

const threadSchema = new mongoose.Schema(
  {
    owner: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: [true, 'Thread must belong to a user.'],
      index: true,
    },
    title: {
      type: String,
      default: null, // Dynamically generated by agent or set by user; null indicates untitled draft
      trim: true,
      maxlength: [
        CHAT_CONSTANTS.TITLE_MAX_LENGTH,
        `Title cannot exceed ${CHAT_CONSTANTS.TITLE_MAX_LENGTH} characters.`,
      ],
    },
    status: {
      type: String,
      enum: CONVERSATION_CONSTANTS.THREAD_STATUSES,
      default: 'active',
      index: true,
    },
    isPinned: {
      type: Boolean,
      default: false,
      index: true,
    },
    activeBranchId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'MessageBranch',
      default: null,
      index: true,
    },
    project: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Project',
      default: null,
      index: true,
    },
    config: {
      type: threadConfigSchema,
      default: () => ({}),
    },
    turnCount: {
      type: Number,
      default: 0,
      min: 0,
    },
    messageCount: {
      type: Number,
      default: 0,
      min: 0,
    },
    lastMessageAt: {
      type: Date,
      default: Date.now,
      index: true,
    },
    isArchived: {
      type: Boolean,
      default: false,
      index: true,
    },
    archivedAt: {
      type: Date,
      default: null,
    },
    isDeleted: {
      type: Boolean,
      default: false,
      index: true,
    },
    deletedAt: {
      type: Date,
      default: null,
    },
    metadata: {
      type: mongoose.Schema.Types.Mixed,
      default: () => ({}),
    },
  },
  BASE_SCHEMA_OPTIONS
);

// Virtual for legacy V0 Chat.user backward compatibility
threadSchema.virtual('user').get(function () {
  return this.owner;
}).set(function (val) {
  this.owner = val;
});

// Compound indexes for performant thread navigation and history pagination
threadSchema.index(
  { owner: 1, isDeleted: 1, isPinned: -1, lastMessageAt: -1 },
  { name: 'idx_thread_owner_active_pinned_activity' }
);

threadSchema.index(
  { owner: 1, status: 1, isDeleted: 1 },
  { name: 'idx_thread_owner_status_deleted' }
);

threadSchema.index(
  { owner: 1, isArchived: 1, archivedAt: -1 },
  { name: 'idx_thread_owner_archived_lifecycle' }
);

/**
 * Statics for lifecycle management
 */
threadSchema.statics.archiveThread = async function (threadId, ownerId) {
  return this.findOneAndUpdate(
    { _id: threadId, owner: ownerId, isDeleted: false },
    {
      $set: {
        status: 'archived',
        isArchived: true,
        archivedAt: new Date(),
      },
    },
    { returnDocument: 'after' }
  );
};

threadSchema.statics.restoreThread = async function (threadId, ownerId) {
  return this.findOneAndUpdate(
    { _id: threadId, owner: ownerId, isDeleted: false },
    {
      $set: {
        status: 'active',
        isArchived: false,
        archivedAt: null,
      },
    },
    { returnDocument: 'after' }
  );
};

threadSchema.statics.softDelete = async function (threadId, ownerId) {
  return this.findOneAndUpdate(
    { _id: threadId, owner: ownerId, isDeleted: false },
    {
      $set: {
        isDeleted: true,
        deletedAt: new Date(),
      },
    },
    { returnDocument: 'after' }
  );
};

export const Thread = mongoose.models.Thread || mongoose.model('Thread', threadSchema);

export default Thread;
